CREATE TABLE IF NOT EXISTS public.db_unidades (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.db_categoria_insumo (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.db_insumos (
  id_insumo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  unidade TEXT NOT NULL,
  categoria TEXT,
  custo_estimado_unitario NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
  estoque_atual NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
  ativo TEXT NOT NULL DEFAULT 'Sim'
);

CREATE UNIQUE INDEX IF NOT EXISTS db_unidades_nome_ci_key
  ON public.db_unidades (lower(btrim(nome)));

CREATE UNIQUE INDEX IF NOT EXISTS db_categoria_insumo_nome_ci_key
  ON public.db_categoria_insumo (lower(btrim(nome)));

CREATE UNIQUE INDEX IF NOT EXISTS db_insumos_nome_ci_key
  ON public.db_insumos (lower(btrim(nome)));

DO $$
DECLARE
  table_name TEXT;
  id_column TEXT;
  sequence_name TEXT;
  maximum_id BIGINT;
  current_sequence_value BIGINT;
BEGIN
  FOR table_name, id_column IN
    SELECT identifiers.table_name, identifiers.id_column
    FROM (VALUES
      ('db_unidades', 'id'),
      ('db_categoria_insumo', 'id'),
      ('db_insumos', 'id_insumo')
    ) AS identifiers(table_name, id_column)
  LOOP
    sequence_name := pg_get_serial_sequence(
      format('public.%I', table_name),
      id_column
    );

    IF sequence_name IS NULL THEN
      sequence_name := format(
        'public.%I',
        table_name || '_' || id_column || '_seq'
      );
      EXECUTE format('CREATE SEQUENCE IF NOT EXISTS %s', sequence_name);
      EXECUTE format(
        'ALTER TABLE public.%I ALTER COLUMN %I SET DEFAULT nextval(%L)',
        table_name,
        id_column,
        sequence_name
      );
      EXECUTE format(
        'ALTER SEQUENCE %s OWNED BY public.%I.%I',
        sequence_name,
        table_name,
        id_column
      );
      EXECUTE format(
        'SELECT COALESCE(MAX(%I), 0) FROM public.%I',
        id_column,
        table_name
      )
      INTO maximum_id;
      EXECUTE format('SELECT last_value FROM %s', sequence_name)
      INTO current_sequence_value;

      IF maximum_id > current_sequence_value THEN
        EXECUTE format('SELECT setval(%L, %s, true)', sequence_name, maximum_id);
      END IF;
    END IF;

    IF table_name <> 'db_unidades' THEN
      EXECUTE format(
        'GRANT USAGE, SELECT ON SEQUENCE %s TO authenticated',
        sequence_name
      );
    END IF;
  END LOOP;
END;
$$;

INSERT INTO public.db_unidades (nome)
SELECT unidade.nome
FROM (VALUES ('un'), ('g'), ('kg'), ('ml'), ('l')) AS unidade(nome)
WHERE NOT EXISTS (
  SELECT 1
  FROM public.db_unidades existente
  WHERE lower(btrim(existente.nome)) = lower(unidade.nome)
);

CREATE OR REPLACE FUNCTION public.sync_db_insumos_categoria_name()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF NEW.nome IS DISTINCT FROM OLD.nome THEN
    UPDATE public.db_insumos
    SET categoria = NEW.nome
    WHERE categoria = OLD.nome;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS db_categoria_insumo_sync_name ON public.db_categoria_insumo;
CREATE TRIGGER db_categoria_insumo_sync_name
AFTER UPDATE OF nome ON public.db_categoria_insumo
FOR EACH ROW
EXECUTE FUNCTION public.sync_db_insumos_categoria_name();

