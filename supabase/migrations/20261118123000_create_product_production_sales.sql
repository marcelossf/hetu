CREATE UNIQUE INDEX IF NOT EXISTS db_insumos_user_id_id_key
  ON public.db_insumos (user_id, id_insumo);

DO $$
DECLARE
  table_name TEXT;
  id_column TEXT;
  owner_id UUID;
  sequence_name TEXT;
  maximum_id BIGINT;
  sequence_value BIGINT;
  sequence_is_called BOOLEAN;
  has_unowned_rows BOOLEAN;
BEGIN
  FOR table_name, id_column IN
    SELECT legacy.table_name, legacy.id_column
    FROM (VALUES
      ('db_fichas', 'id_ficha'),
      ('db_fichas_itens', 'id_item'),
      ('db_canais_vendas', 'id'),
      ('db_producao', 'id_producao'),
      ('db_producao_itens', 'id_item'),
      ('db_ajustes_estoque_produto', 'id_ajuste'),
      ('db_vendas_cabecalho', 'id'),
      ('db_vendas_itens', 'id_venda_item'),
      ('db_vendas_pagamentos', 'id_pagamento')
    ) AS legacy(table_name, id_column)
  LOOP
    IF to_regclass(format('public.%I', table_name)) IS NULL THEN
      CONTINUE;
    END IF;

    EXECUTE format(
      'ALTER TABLE public.%I ADD COLUMN IF NOT EXISTS user_id UUID REFERENCES auth.users (id) ON DELETE CASCADE',
      table_name
    );

    EXECUTE format(
      'SELECT EXISTS (SELECT 1 FROM public.%I WHERE user_id IS NULL)',
      table_name
    )
    INTO has_unowned_rows;

    IF has_unowned_rows THEN
      IF owner_id IS NULL THEN
        SELECT id
        INTO owner_id
        FROM auth.users
        WHERE deleted_at IS NULL
        ORDER BY created_at, id
        LIMIT 1;
      END IF;

      IF owner_id IS NULL THEN
        RAISE EXCEPTION
          'Cannot migrate legacy table public.%: no active Supabase users exist',
          table_name;
      END IF;

      EXECUTE format(
        'UPDATE public.%I SET user_id = $1 WHERE user_id IS NULL',
        table_name
      )
      USING owner_id;
    END IF;

    EXECUTE format(
      'ALTER TABLE public.%I ALTER COLUMN user_id SET DEFAULT auth.uid(), ALTER COLUMN user_id SET NOT NULL',
      table_name
    );

    sequence_name := pg_get_serial_sequence(
      format('public.%I', table_name),
      id_column
    );

    IF sequence_name IS NULL THEN
      sequence_name := format(
        'public.%I',
        table_name || '_' || id_column || '_seq'
      );
      EXECUTE format('CREATE SEQUENCE IF NOT EXISTS %s', sequence_name);
      EXECUTE format(
        'ALTER TABLE public.%I ALTER COLUMN %I SET DEFAULT nextval(%L)',
        table_name,
        id_column,
        sequence_name
      );
      EXECUTE format(
        'ALTER SEQUENCE %s OWNED BY public.%I.%I',
        sequence_name,
        table_name,
        id_column
      );
    END IF;

    EXECUTE format(
      'SELECT MAX(%I) FROM public.%I',
      id_column,
      table_name
    )
    INTO maximum_id;

    EXECUTE format(
      'SELECT last_value, is_called FROM %s',
      sequence_name
    )
    INTO sequence_value, sequence_is_called;

    IF maximum_id IS NOT NULL AND (
      sequence_value < maximum_id
      OR (sequence_value = maximum_id AND NOT sequence_is_called)
    ) THEN
      PERFORM setval(sequence_name::regclass, maximum_id, true);
    END IF;
  END LOOP;
END;
$$;

