CREATE OR REPLACE FUNCTION public.save_ficha(
  p_id_ficha INT,
  p_nome_receita TEXT,
  p_rendimento NUMERIC,
  p_id_categoria INT,
  p_custo_embalagem NUMERIC,
  p_custo_mao_obra NUMERIC,
  p_custo_armazenamento NUMERIC,
  p_preco_venda NUMERIC,
  p_ativo TEXT,
  p_itens JSONB
)
RETURNS INT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_user_id UUID := auth.uid();
  v_id_ficha INT;
  v_item_count INT;
  v_valid_item_count INT;
  v_custo_insumos NUMERIC;
  v_custo_total NUMERIC;
  v_item RECORD;
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'AUTH_REQUIRED' USING ERRCODE = '42501';
  END IF;
  IF p_nome_receita IS NULL OR btrim(p_nome_receita) = ''
    OR length(btrim(p_nome_receita)) > 120
    OR p_rendimento IS NULL OR p_rendimento <= 0
    OR p_rendimento > 99999999.99
    OR pg_catalog.round(p_rendimento, 2) <> p_rendimento
    OR p_custo_embalagem IS NULL OR p_custo_embalagem < 0
    OR p_custo_embalagem > 99999999.99
    OR pg_catalog.round(p_custo_embalagem, 2) <> p_custo_embalagem
    OR p_custo_mao_obra IS NULL OR p_custo_mao_obra < 0
    OR p_custo_mao_obra > 99999999.99
    OR pg_catalog.round(p_custo_mao_obra, 2) <> p_custo_mao_obra
    OR p_custo_armazenamento IS NULL OR p_custo_armazenamento < 0
    OR p_custo_armazenamento > 99999999.99
    OR pg_catalog.round(p_custo_armazenamento, 2) <> p_custo_armazenamento
    OR p_preco_venda IS NULL OR p_preco_venda < 0
    OR p_preco_venda > 99999999.99
    OR pg_catalog.round(p_preco_venda, 2) <> p_preco_venda
    OR p_ativo NOT IN ('Sim', 'Não')
  THEN
    RAISE EXCEPTION 'INVALID_PRODUCT_DATA' USING ERRCODE = '22023';
  END IF;
  IF p_itens IS NULL OR pg_catalog.jsonb_typeof(p_itens) <> 'array' THEN
    RAISE EXCEPTION 'INVALID_RECIPE_ITEMS' USING ERRCODE = '22023';
  END IF;

  v_item_count := pg_catalog.jsonb_array_length(p_itens);
  IF v_item_count = 0 OR v_item_count > 100 THEN
    RAISE EXCEPTION 'TOO_MANY_RECIPE_ITEMS' USING ERRCODE = '22023';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM pg_catalog.jsonb_to_recordset(p_itens)
      AS requested(id_insumo INT, quantidade NUMERIC)
    WHERE requested.id_insumo IS NULL
      OR requested.quantidade IS NULL
      OR requested.quantidade <= 0
      OR requested.quantidade > 99999999.9999
      OR pg_catalog.round(requested.quantidade, 4) <> requested.quantidade
      OR pg_catalog.round(requested.quantidade / p_rendimento, 4) <= 0
      OR pg_catalog.round(requested.quantidade / p_rendimento, 4) > 999999.9999
  ) THEN
    RAISE EXCEPTION 'INVALID_RECIPE_ITEM' USING ERRCODE = '22023';
  END IF;
  IF EXISTS (
    SELECT requested.id_insumo
    FROM pg_catalog.jsonb_to_recordset(p_itens)
      AS requested(id_insumo INT, quantidade NUMERIC)
    GROUP BY requested.id_insumo
    HAVING pg_catalog.count(*) > 1
  ) THEN
    RAISE EXCEPTION 'DUPLICATE_RECIPE_INGREDIENT' USING ERRCODE = '22023';
  END IF;

  SELECT pg_catalog.count(*)
  INTO v_valid_item_count
  FROM pg_catalog.jsonb_to_recordset(p_itens)
    AS requested(id_insumo INT, quantidade NUMERIC)
  JOIN public.db_insumos AS supply
    ON supply.id_insumo = requested.id_insumo
   AND supply.user_id = v_user_id
   AND supply.ativo = 'Sim';
  IF v_valid_item_count <> v_item_count THEN
    RAISE EXCEPTION 'INGREDIENT_NOT_FOUND_OR_INACTIVE' USING ERRCODE = '22023';
  END IF;

  IF p_id_categoria IS NOT NULL AND NOT EXISTS (
    SELECT 1
    FROM public.db_categoria_produto AS category
    WHERE category.id = p_id_categoria
      AND category.user_id = v_user_id
  ) THEN
    RAISE EXCEPTION 'PRODUCT_CATEGORY_NOT_FOUND' USING ERRCODE = '22023';
  END IF;

  SELECT pg_catalog.round(
    COALESCE(
      pg_catalog.sum(
        pg_catalog.round(requested.quantidade / p_rendimento, 4)
        * supply.custo_estimado_unitario
      ),
      0
    ),
    2
  )
  INTO v_custo_insumos
  FROM pg_catalog.jsonb_to_recordset(p_itens)
    AS requested(id_insumo INT, quantidade NUMERIC)
  JOIN public.db_insumos AS supply
    ON supply.id_insumo = requested.id_insumo
   AND supply.user_id = v_user_id;

  v_custo_total := pg_catalog.round(
    v_custo_insumos +
    p_custo_embalagem / p_rendimento +
    p_custo_mao_obra / p_rendimento +
    p_custo_armazenamento / p_rendimento,
    2
  );
  IF v_custo_total > 99999999.99 THEN
    RAISE EXCEPTION 'INVALID_PRODUCT_DATA' USING ERRCODE = '22023';
  END IF;

  IF p_id_ficha IS NULL THEN
    INSERT INTO public.db_fichas (
      user_id,
      nome_receita,
      rendimento,
      custo_embalagem,
      custo_mao_obra,
      custo_armazenamento,
      custo_total,
      custo_unitario,
      id_categoria,
      preco_venda,
      ativo
    )
    VALUES (
      v_user_id,
      btrim(p_nome_receita),
      1,
      pg_catalog.round(p_custo_embalagem / p_rendimento, 2),
      pg_catalog.round(p_custo_mao_obra / p_rendimento, 2),
      pg_catalog.round(p_custo_armazenamento / p_rendimento, 2),
      v_custo_total,
      v_custo_total,
      p_id_categoria,
      p_preco_venda,
      p_ativo
    )
    RETURNING id_ficha INTO v_id_ficha;
  ELSE
    UPDATE public.db_fichas
    SET
      nome_receita = btrim(p_nome_receita),
      rendimento = 1,
      custo_embalagem = pg_catalog.round(p_custo_embalagem / p_rendimento, 2),
      custo_mao_obra = pg_catalog.round(p_custo_mao_obra / p_rendimento, 2),
      custo_armazenamento = pg_catalog.round(p_custo_armazenamento / p_rendimento, 2),
      custo_total = v_custo_total,
      custo_unitario = v_custo_total,
      id_categoria = p_id_categoria,
      preco_venda = p_preco_venda,
      ativo = p_ativo
    WHERE id_ficha = p_id_ficha
      AND user_id = v_user_id
    RETURNING id_ficha INTO v_id_ficha;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'PRODUCT_NOT_FOUND' USING ERRCODE = 'P0002';
    END IF;
    DELETE FROM public.db_fichas_itens
    WHERE id_ficha = v_id_ficha
      AND user_id = v_user_id;
  END IF;

  FOR v_item IN
    SELECT requested.id_insumo, requested.quantidade
    FROM pg_catalog.jsonb_to_recordset(p_itens)
      AS requested(id_insumo INT, quantidade NUMERIC)
    ORDER BY requested.id_insumo
  LOOP
    INSERT INTO public.db_fichas_itens (
      user_id,
      id_ficha,
      id_insumo,
      qtd_insumo
    )
    VALUES (
      v_user_id,
      v_id_ficha,
      v_item.id_insumo,
      pg_catalog.round(v_item.quantidade / p_rendimento, 4)
    );
  END LOOP;

  RETURN v_id_ficha;
END;
$$;

CREATE OR REPLACE FUNCTION public.adjust_product_stock(
  p_id_ficha INT,
  p_quantidade_delta NUMERIC,
  p_motivo TEXT
)
RETURNS NUMERIC
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_user_id UUID := auth.uid();
  v_stock NUMERIC(10, 2);
  v_new_stock NUMERIC(10, 2);
  v_tipo TEXT;
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'AUTH_REQUIRED' USING ERRCODE = '42501';
  END IF;
  IF p_quantidade_delta IS NULL
    OR p_quantidade_delta = 0
    OR pg_catalog.round(p_quantidade_delta, 2) <> p_quantidade_delta
    OR p_motivo IS NULL
    OR btrim(p_motivo) = ''
    OR length(btrim(p_motivo)) > 300
  THEN
    RAISE EXCEPTION 'INVALID_STOCK_ADJUSTMENT' USING ERRCODE = '22023';
  END IF;

  SELECT product.estoque_atual
  INTO v_stock
  FROM public.db_fichas AS product
  WHERE product.id_ficha = p_id_ficha
    AND product.user_id = v_user_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'PRODUCT_NOT_FOUND' USING ERRCODE = 'P0002';
  END IF;

  v_new_stock := v_stock + p_quantidade_delta;
  IF v_new_stock < 0 THEN
    RAISE EXCEPTION 'INSUFFICIENT_PRODUCT_STOCK' USING ERRCODE = '22023';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public.db_ajustes_estoque_produto AS adjustment
    WHERE adjustment.user_id = v_user_id
      AND adjustment.id_ficha = p_id_ficha
  ) AND NOT EXISTS (
    SELECT 1
    FROM public.db_producao AS production
    WHERE production.user_id = v_user_id
      AND production.id_produto = p_id_ficha
  ) AND NOT EXISTS (
    SELECT 1
    FROM public.db_vendas_itens AS sale_item
    WHERE sale_item.user_id = v_user_id
      AND sale_item.id_produto = p_id_ficha
  ) THEN
    v_tipo := 'saldo_inicial';
  ELSE
    v_tipo := 'ajuste';
  END IF;

  INSERT INTO public.db_ajustes_estoque_produto (
    user_id,
    id_ficha,
    tipo,
    quantidade_delta,
    motivo
  )
  VALUES (v_user_id, p_id_ficha, v_tipo, p_quantidade_delta, btrim(p_motivo));

  UPDATE public.db_fichas
  SET estoque_atual = v_new_stock
  WHERE id_ficha = p_id_ficha
    AND user_id = v_user_id;

  RETURN v_new_stock;
END;
$$;

CREATE OR REPLACE FUNCTION public.register_production(
  p_id_produto INT,
  p_quantidade NUMERIC,
  p_observacao TEXT
)
RETURNS INT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_user_id UUID := auth.uid();
  v_product RECORD;
  v_item RECORD;
  v_id_producao INT;
  v_qtd_consumida NUMERIC;
  v_custo_total NUMERIC;
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'AUTH_REQUIRED' USING ERRCODE = '42501';
  END IF;
  IF p_quantidade IS NULL
    OR p_quantidade <= 0
    OR pg_catalog.round(p_quantidade, 2) <> p_quantidade
    OR p_observacao IS NOT NULL AND length(p_observacao) > 1000
  THEN
    RAISE EXCEPTION 'INVALID_PRODUCTION_DATA' USING ERRCODE = '22023';
  END IF;

  SELECT
    product.id_ficha,
    product.custo_unitario,
    product.estoque_atual,
    product.ativo
  INTO v_product
  FROM public.db_fichas AS product
  WHERE product.id_ficha = p_id_produto
    AND product.user_id = v_user_id
  FOR UPDATE;
  IF NOT FOUND OR v_product.ativo <> 'Sim' THEN
    RAISE EXCEPTION 'PRODUCT_NOT_FOUND_OR_INACTIVE' USING ERRCODE = 'P0002';
  END IF;
  IF v_product.estoque_atual + p_quantidade > 99999999.99 THEN
    RAISE EXCEPTION 'INVALID_PRODUCTION_DATA' USING ERRCODE = '22023';
  END IF;

  v_custo_total := pg_catalog.round(
    v_product.custo_unitario * p_quantidade,
    2
  );
  IF v_custo_total > 99999999.99 THEN
    RAISE EXCEPTION 'INVALID_PRODUCTION_DATA' USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.db_producao (
    user_id,
    id_produto,
    qtd_produzida,
    custo_unitario_momento,
    custo_total_lote,
    observacao
  )
  VALUES (
    v_user_id,
    p_id_produto,
    p_quantidade,
    v_product.custo_unitario,
    v_custo_total,
    NULLIF(btrim(COALESCE(p_observacao, '')), '')
  )
  RETURNING id_producao INTO v_id_producao;

  FOR v_item IN
    SELECT
      recipe.id_insumo,
      recipe.qtd_insumo,
      supply.nome,
      supply.estoque_atual,
      supply.custo_estimado_unitario
    FROM public.db_fichas_itens AS recipe
    JOIN public.db_insumos AS supply
      ON supply.id_insumo = recipe.id_insumo
     AND supply.user_id = recipe.user_id
    WHERE recipe.user_id = v_user_id
      AND recipe.id_ficha = p_id_produto
    ORDER BY recipe.id_insumo
    FOR UPDATE OF supply
  LOOP
    v_qtd_consumida := pg_catalog.round(v_item.qtd_insumo * p_quantidade, 4);
    IF v_item.estoque_atual < v_qtd_consumida THEN
      RAISE EXCEPTION 'INSUFFICIENT_INGREDIENT:%', v_item.nome
        USING ERRCODE = '22023';
    END IF;

    UPDATE public.db_insumos
    SET estoque_atual = estoque_atual - v_qtd_consumida
    WHERE id_insumo = v_item.id_insumo
      AND user_id = v_user_id;

    v_custo_total := pg_catalog.round(
      v_qtd_consumida * v_item.custo_estimado_unitario,
      2
    );
    IF v_custo_total > 99999999.99 THEN
      RAISE EXCEPTION 'INVALID_PRODUCTION_DATA' USING ERRCODE = '22023';
    END IF;
    INSERT INTO public.db_producao_itens (
      user_id,
      id_producao,
      id_insumo,
      qtd_consumida,
      custo_unitario_momento,
      custo_total
    )
    VALUES (
      v_user_id,
      v_id_producao,
      v_item.id_insumo,
      v_qtd_consumida,
      v_item.custo_estimado_unitario,
      v_custo_total
    );
  END LOOP;

  UPDATE public.db_fichas
  SET estoque_atual = estoque_atual + p_quantidade
  WHERE id_ficha = p_id_produto
    AND user_id = v_user_id;

  RETURN v_id_producao;
END;
$$;

CREATE OR REPLACE FUNCTION public.register_sale(
  p_id_canal INT,
  p_subtotal NUMERIC,
  p_desconto NUMERIC,
  p_observacoes TEXT,
  p_itens JSONB,
  p_pagamentos JSONB
)
RETURNS INT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_user_id UUID := auth.uid();
  v_locked_items JSONB;
  v_item_count INT;
  v_payment_count INT;
  v_payment_total NUMERIC;
  v_subtotal NUMERIC := 0;
  v_total NUMERIC;
  v_id_venda INT;
  v_item RECORD;
  v_payment RECORD;
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'AUTH_REQUIRED' USING ERRCODE = '42501';
  END IF;
  IF NOT EXISTS (
    SELECT 1
    FROM public.db_canais_vendas AS channel
    WHERE channel.id = p_id_canal
      AND channel.user_id = v_user_id
      AND channel.ativo = 'Sim'
  ) THEN
    RAISE EXCEPTION 'SALES_CHANNEL_NOT_FOUND_OR_INACTIVE' USING ERRCODE = '22023';
  END IF;
  IF p_itens IS NULL OR pg_catalog.jsonb_typeof(p_itens) <> 'array' THEN
    RAISE EXCEPTION 'INVALID_SALE_ITEMS' USING ERRCODE = '22023';
  END IF;
  v_item_count := pg_catalog.jsonb_array_length(p_itens);
  IF v_item_count = 0 OR v_item_count > 100 THEN
    RAISE EXCEPTION 'INVALID_SALE_ITEM_COUNT' USING ERRCODE = '22023';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM pg_catalog.jsonb_to_recordset(p_itens)
      AS requested(id_produto INT, quantidade NUMERIC)
    WHERE requested.id_produto IS NULL
      OR requested.quantidade IS NULL
      OR requested.quantidade <= 0
      OR requested.quantidade > 99999999.99
      OR pg_catalog.round(requested.quantidade, 2) <> requested.quantidade
  ) THEN
    RAISE EXCEPTION 'INVALID_SALE_ITEM' USING ERRCODE = '22023';
  END IF;
  IF EXISTS (
    SELECT requested.id_produto
    FROM pg_catalog.jsonb_to_recordset(p_itens)
      AS requested(id_produto INT, quantidade NUMERIC)
    GROUP BY requested.id_produto
    HAVING pg_catalog.count(*) > 1
  ) THEN
    RAISE EXCEPTION 'DUPLICATE_SALE_PRODUCT' USING ERRCODE = '22023';
  END IF;
  IF p_observacoes IS NOT NULL AND length(p_observacoes) > 1000 THEN
    RAISE EXCEPTION 'INVALID_SALE_NOTES' USING ERRCODE = '22023';
  END IF;

  v_locked_items := '[]'::JSONB;
  FOR v_item IN
    SELECT
      product.id_ficha AS id_produto,
      product.nome_receita AS nome_produto,
      requested.quantidade,
      product.preco_venda AS preco_venda_unitario,
      product.custo_unitario AS custo_unitario_historico,
      product.estoque_atual
    FROM pg_catalog.jsonb_to_recordset(p_itens)
      AS requested(id_produto INT, quantidade NUMERIC)
    JOIN public.db_fichas AS product
      ON product.id_ficha = requested.id_produto
     AND product.user_id = v_user_id
    WHERE product.ativo = 'Sim'
    ORDER BY product.id_ficha
    FOR UPDATE OF product
  LOOP
    v_locked_items := v_locked_items || pg_catalog.jsonb_build_array(
      pg_catalog.jsonb_build_object(
        'id_produto', v_item.id_produto,
        'nome_produto', v_item.nome_produto,
        'quantidade', v_item.quantidade,
        'preco_venda_unitario', v_item.preco_venda_unitario,
        'custo_unitario_historico', v_item.custo_unitario_historico,
        'estoque_atual', v_item.estoque_atual
      )
    );
  END LOOP;

  IF COALESCE(pg_catalog.jsonb_array_length(v_locked_items), 0) <> v_item_count THEN
    RAISE EXCEPTION 'PRODUCT_NOT_FOUND_OR_INACTIVE' USING ERRCODE = '22023';
  END IF;

  FOR v_item IN
    SELECT *
    FROM pg_catalog.jsonb_to_recordset(v_locked_items)
      AS sale_item(
        id_produto INT,
        nome_produto TEXT,
        quantidade NUMERIC,
        preco_venda_unitario NUMERIC,
        custo_unitario_historico NUMERIC,
        estoque_atual NUMERIC
      )
  LOOP
    IF v_item.estoque_atual < v_item.quantidade THEN
      RAISE EXCEPTION 'INSUFFICIENT_PRODUCT_STOCK:%', v_item.nome_produto
        USING ERRCODE = '22023';
    END IF;
    v_subtotal := v_subtotal + pg_catalog.round(
      v_item.quantidade * v_item.preco_venda_unitario,
      2
    );
    IF v_subtotal > 99999999.99 THEN
      RAISE EXCEPTION 'SALE_TOTAL_CHANGED_OR_INVALID_DISCOUNT'
        USING ERRCODE = '22023';
    END IF;
  END LOOP;

  IF p_subtotal IS NULL
    OR pg_catalog.round(p_subtotal, 2) <> v_subtotal
    OR p_desconto IS NULL
    OR pg_catalog.round(p_desconto, 2) <> p_desconto
    OR p_desconto < 0
    OR p_desconto > v_subtotal
  THEN
    RAISE EXCEPTION 'SALE_TOTAL_CHANGED_OR_INVALID_DISCOUNT' USING ERRCODE = '22023';
  END IF;

  v_total := v_subtotal - p_desconto;
  IF p_pagamentos IS NULL OR pg_catalog.jsonb_typeof(p_pagamentos) <> 'array' THEN
    RAISE EXCEPTION 'INVALID_SALE_PAYMENTS' USING ERRCODE = '22023';
  END IF;
  IF pg_catalog.jsonb_array_length(p_pagamentos) > 100 THEN
    RAISE EXCEPTION 'INVALID_SALE_PAYMENTS' USING ERRCODE = '22023';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM pg_catalog.jsonb_to_recordset(p_pagamentos)
      AS payment(forma_pagamento TEXT, valor NUMERIC)
    WHERE payment.forma_pagamento IS NULL
      OR payment.forma_pagamento NOT IN (
        'pix',
        'dinheiro',
        'cartao_debito',
        'cartao_credito',
        'transferencia',
        'outro'
      )
      OR payment.valor IS NULL
      OR payment.valor <= 0
      OR payment.valor > 99999999.99
      OR pg_catalog.round(payment.valor, 2) <> payment.valor
  ) THEN
    RAISE EXCEPTION 'INVALID_SALE_PAYMENT' USING ERRCODE = '22023';
  END IF;
  SELECT
    pg_catalog.count(*),
    pg_catalog.round(COALESCE(pg_catalog.sum(payment.valor), 0), 2)
  INTO v_payment_count, v_payment_total
  FROM pg_catalog.jsonb_to_recordset(p_pagamentos)
    AS payment(forma_pagamento TEXT, valor NUMERIC);

  IF (v_total = 0 AND v_payment_count <> 0)
    OR (v_total > 0 AND (v_payment_count = 0 OR v_payment_total <> v_total))
  THEN
    RAISE EXCEPTION 'SALE_PAYMENTS_DO_NOT_MATCH_TOTAL' USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.db_vendas_cabecalho (
    user_id,
    id_canal,
    subtotal_pedido,
    desconto,
    valor_total_pedido,
    observacoes
  )
  VALUES (
    v_user_id,
    p_id_canal,
    v_subtotal,
    p_desconto,
    v_total,
    NULLIF(btrim(COALESCE(p_observacoes, '')), '')
  )
  RETURNING id INTO v_id_venda;

  FOR v_item IN
    SELECT *
    FROM pg_catalog.jsonb_to_recordset(v_locked_items)
      AS sale_item(
        id_produto INT,
        nome_produto TEXT,
        quantidade NUMERIC,
        preco_venda_unitario NUMERIC,
        custo_unitario_historico NUMERIC,
        estoque_atual NUMERIC
      )
  LOOP
    INSERT INTO public.db_vendas_itens (
      user_id,
      id_venda,
      id_produto,
      nome_produto,
      quantidade,
      preco_venda_unitario,
      custo_unitario_historico,
      subtotal
    )
    VALUES (
      v_user_id,
      v_id_venda,
      v_item.id_produto,
      v_item.nome_produto,
      v_item.quantidade,
      v_item.preco_venda_unitario,
      v_item.custo_unitario_historico,
      pg_catalog.round(v_item.quantidade * v_item.preco_venda_unitario, 2)
    );

    UPDATE public.db_fichas
    SET estoque_atual = estoque_atual - v_item.quantidade
    WHERE id_ficha = v_item.id_produto
      AND user_id = v_user_id;
  END LOOP;

  FOR v_payment IN
    SELECT payment.forma_pagamento, payment.valor
    FROM pg_catalog.jsonb_to_recordset(p_pagamentos)
      AS payment(forma_pagamento TEXT, valor NUMERIC)
  LOOP
    INSERT INTO public.db_vendas_pagamentos (
      user_id,
      id_venda,
      forma_pagamento,
      valor
    )
    VALUES (
      v_user_id,
      v_id_venda,
      v_payment.forma_pagamento,
      v_payment.valor
    );
  END LOOP;

  RETURN v_id_venda;
END;
$$;

CREATE OR REPLACE FUNCTION public.cancel_sale(
  p_id_venda INT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_user_id UUID := auth.uid();
  v_status TEXT;
  v_item RECORD;
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'AUTH_REQUIRED' USING ERRCODE = '42501';
  END IF;

  SELECT sale.status
  INTO v_status
  FROM public.db_vendas_cabecalho AS sale
  WHERE sale.id = p_id_venda
    AND sale.user_id = v_user_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'SALE_NOT_FOUND' USING ERRCODE = 'P0002';
  END IF;
  IF v_status <> 'concluida' THEN
    RAISE EXCEPTION 'SALE_ALREADY_CANCELLED' USING ERRCODE = '22023';
  END IF;

  FOR v_item IN
    SELECT sale_item.id_produto, sale_item.quantidade
    FROM public.db_vendas_itens AS sale_item
    WHERE sale_item.id_venda = p_id_venda
      AND sale_item.user_id = v_user_id
    ORDER BY sale_item.id_produto
  LOOP
    UPDATE public.db_fichas
    SET estoque_atual = estoque_atual + v_item.quantidade
    WHERE id_ficha = v_item.id_produto
      AND user_id = v_user_id;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'SALE_PRODUCT_NOT_FOUND' USING ERRCODE = 'P0002';
    END IF;
  END LOOP;

  UPDATE public.db_vendas_cabecalho
  SET status = 'cancelada', cancelada_em = NOW()
  WHERE id = p_id_venda
    AND user_id = v_user_id;

  RETURN TRUE;
END;
$$;

