CREATE OR REPLACE FUNCTION public.recalculate_recipe_cost_after_supply_change(
  p_user_id UUID,
  p_id_insumo INT,
  p_preco_anterior NUMERIC,
  p_preco_novo NUMERIC,
  p_id_compra INT,
  p_id_lote UUID,
  p_tipo_movimento TEXT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_recipe RECORD;
  v_new_cost NUMERIC;
BEGIN
  FOR v_recipe IN
    SELECT item.id_ficha
    FROM public.db_fichas_itens AS item
    JOIN public.db_fichas AS recipe
      ON recipe.user_id = item.user_id
     AND recipe.id_ficha = item.id_ficha
    WHERE item.user_id = p_user_id
      AND item.id_insumo = p_id_insumo
    ORDER BY item.id_ficha
    FOR UPDATE OF recipe
  LOOP
    SELECT pg_catalog.round(
      COALESCE(
        pg_catalog.sum(item.qtd_insumo * supply.custo_estimado_unitario),
        0
      ) + recipe.custo_embalagem
        + recipe.custo_mao_obra
        + recipe.custo_armazenamento,
      2
    )
    INTO v_new_cost
    FROM public.db_fichas AS recipe
    LEFT JOIN public.db_fichas_itens AS item
      ON item.user_id = recipe.user_id
     AND item.id_ficha = recipe.id_ficha
    LEFT JOIN public.db_insumos AS supply
      ON supply.user_id = item.user_id
     AND supply.id_insumo = item.id_insumo
    WHERE recipe.user_id = p_user_id
      AND recipe.id_ficha = v_recipe.id_ficha
    GROUP BY
      recipe.id_ficha,
      recipe.user_id,
      recipe.custo_embalagem,
      recipe.custo_mao_obra,
      recipe.custo_armazenamento;

    IF v_new_cost < 0 OR v_new_cost > 99999999.99 THEN
      RAISE EXCEPTION 'INVALID_RECIPE_COST' USING ERRCODE = '22023';
    END IF;

    INSERT INTO public.db_fichas_historico_custos (
      user_id,
      id_ficha,
      id_insumo_alterado,
      preco_insumo_anterior,
      preco_insumo_novo,
      impacto_diferenca_brl,
      novo_custo_total_ficha,
      id_compra_origem,
      id_lote_compra,
      tipo_movimento
    )
    SELECT
      p_user_id,
      recipe.id_ficha,
      p_id_insumo,
      p_preco_anterior,
      p_preco_novo,
      pg_catalog.round(
        (p_preco_novo - p_preco_anterior) * item.qtd_insumo,
        2
      ),
      v_new_cost,
      p_id_compra,
      p_id_lote,
      p_tipo_movimento
    FROM public.db_fichas AS recipe
    JOIN public.db_fichas_itens AS item
      ON item.user_id = recipe.user_id
     AND item.id_ficha = recipe.id_ficha
     AND item.id_insumo = p_id_insumo
    WHERE recipe.user_id = p_user_id
      AND recipe.id_ficha = v_recipe.id_ficha;

    UPDATE public.db_fichas
    SET custo_total = v_new_cost, custo_unitario = v_new_cost
    WHERE user_id = p_user_id
      AND id_ficha = v_recipe.id_ficha;
  END LOOP;
END;
$$;

REVOKE ALL ON FUNCTION public.recalculate_recipe_cost_after_supply_change(
  UUID, INT, NUMERIC, NUMERIC, INT, UUID, TEXT
) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.register_purchase_batch(
  p_id_fornecedor INT,
  p_data_compra DATE,
  p_itens JSONB
)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_user_id UUID := auth.uid();
  v_id_lote UUID := gen_random_uuid();
  v_item_count INT;
  v_item RECORD;
  v_new_stock NUMERIC;
  v_new_cost NUMERIC;
  v_id_compra INT;
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'AUTH_REQUIRED' USING ERRCODE = '42501';
  END IF;
  IF p_id_fornecedor IS NULL OR p_data_compra IS NULL
    OR p_itens IS NULL OR pg_catalog.jsonb_typeof(p_itens) <> 'array'
  THEN
    RAISE EXCEPTION 'INVALID_PURCHASE_DATA' USING ERRCODE = '22023';
  END IF;

  PERFORM supplier.id_fornecedor
  FROM public.db_fornecedores AS supplier
  WHERE supplier.user_id = v_user_id
    AND supplier.id_fornecedor = p_id_fornecedor
    AND supplier.ativo = 'Sim'
  FOR SHARE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'SUPPLIER_NOT_FOUND_OR_INACTIVE' USING ERRCODE = '22023';
  END IF;

  v_item_count := pg_catalog.jsonb_array_length(p_itens);
  IF v_item_count < 1 OR v_item_count > 100 THEN
    RAISE EXCEPTION 'INVALID_PURCHASE_ITEM_COUNT' USING ERRCODE = '22023';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM pg_catalog.jsonb_to_recordset(p_itens)
      AS requested(id_insumo INT, quantidade NUMERIC, valor_total NUMERIC)
    WHERE requested.id_insumo IS NULL
      OR requested.quantidade IS NULL
      OR requested.quantidade <= 0
      OR requested.quantidade > 99999999.9999
      OR pg_catalog.round(requested.quantidade, 4) <> requested.quantidade
      OR requested.valor_total IS NULL
      OR requested.valor_total <= 0
      OR requested.valor_total > 99999999.99
      OR pg_catalog.round(requested.valor_total, 2) <> requested.valor_total
  ) THEN
    RAISE EXCEPTION 'INVALID_PURCHASE_ITEM' USING ERRCODE = '22023';
  END IF;
  IF EXISTS (
    SELECT requested.id_insumo
    FROM pg_catalog.jsonb_to_recordset(p_itens)
      AS requested(id_insumo INT, quantidade NUMERIC, valor_total NUMERIC)
    GROUP BY requested.id_insumo
    HAVING pg_catalog.count(*) > 1
  ) THEN
    RAISE EXCEPTION 'DUPLICATE_PURCHASE_SUPPLY' USING ERRCODE = '22023';
  END IF;

  FOR v_item IN
    SELECT
      requested.id_insumo,
      requested.quantidade,
      requested.valor_total,
      supply.estoque_atual,
      supply.custo_estimado_unitario,
      supply.unidade
    FROM pg_catalog.jsonb_to_recordset(p_itens)
      AS requested(id_insumo INT, quantidade NUMERIC, valor_total NUMERIC)
    JOIN public.db_insumos AS supply
      ON supply.user_id = v_user_id
     AND supply.id_insumo = requested.id_insumo
     AND supply.ativo = 'Sim'
    ORDER BY requested.id_insumo
    FOR UPDATE OF supply
  LOOP
    v_new_stock := v_item.estoque_atual + v_item.quantidade;
    IF v_new_stock > 99999999.9999 THEN
      RAISE EXCEPTION 'INVALID_RESULTING_SUPPLY_STOCK' USING ERRCODE = '22023';
    END IF;
    v_new_cost := pg_catalog.round(
      (
        v_item.estoque_atual * v_item.custo_estimado_unitario
        + v_item.valor_total
      ) / v_new_stock,
      2
    );
    IF v_new_cost < 0 OR v_new_cost > 99999999.99 THEN
      RAISE EXCEPTION 'INVALID_RESULTING_SUPPLY_COST' USING ERRCODE = '22023';
    END IF;

    UPDATE public.db_insumos
    SET
      estoque_atual = v_new_stock,
      custo_estimado_unitario = v_new_cost
    WHERE user_id = v_user_id
      AND id_insumo = v_item.id_insumo;

    INSERT INTO public.db_compras_historico (
      user_id,
      id_lote,
      data_compra,
      id_insumo,
      id_fornecedor,
      quantidade,
      unidade_compra,
      valor_total,
      valor_unitario
    )
    VALUES (
      v_user_id,
      v_id_lote,
      p_data_compra::TIMESTAMPTZ,
      v_item.id_insumo,
      p_id_fornecedor,
      v_item.quantidade,
      v_item.unidade,
      v_item.valor_total,
      pg_catalog.round(v_item.valor_total / v_item.quantidade, 2)
    )
    RETURNING id_compra INTO v_id_compra;

    PERFORM public.recalculate_recipe_cost_after_supply_change(
      v_user_id,
      v_item.id_insumo,
      v_item.custo_estimado_unitario,
      v_new_cost,
      v_id_compra,
      v_id_lote,
      'compra'
    );
  END LOOP;

  IF (
    SELECT pg_catalog.count(*)
    FROM public.db_compras_historico AS purchase
    WHERE purchase.user_id = v_user_id
      AND purchase.id_lote = v_id_lote
  ) <> v_item_count THEN
    RAISE EXCEPTION 'SUPPLY_NOT_FOUND_OR_INACTIVE' USING ERRCODE = '22023';
  END IF;

  RETURN v_id_lote;
END;
$$;

CREATE OR REPLACE FUNCTION public.cancel_purchase_batch(
  p_id_lote UUID,
  p_motivo TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_user_id UUID := auth.uid();
  v_item RECORD;
  v_supply RECORD;
  v_new_stock NUMERIC;
  v_remaining_value NUMERIC;
  v_new_cost NUMERIC;
  v_cancelled_id INT;
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'AUTH_REQUIRED' USING ERRCODE = '42501';
  END IF;
  IF p_id_lote IS NULL
    OR p_motivo IS NULL
    OR btrim(p_motivo) = ''
    OR length(btrim(p_motivo)) > 300
  THEN
    RAISE EXCEPTION 'INVALID_PURCHASE_CANCELLATION' USING ERRCODE = '22023';
  END IF;

  PERFORM purchase.id_compra
  FROM public.db_compras_historico AS purchase
  WHERE purchase.user_id = v_user_id
    AND purchase.id_lote = p_id_lote
    AND purchase.tipo_movimento = 'compra'
  ORDER BY purchase.id_compra
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'PURCHASE_NOT_FOUND' USING ERRCODE = 'P0002';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM public.db_compras_historico AS purchase
    WHERE purchase.user_id = v_user_id
      AND purchase.id_lote = p_id_lote
      AND purchase.tipo_movimento = 'compra'
      AND purchase.status <> 'registrada'
  ) THEN
    RAISE EXCEPTION 'PURCHASE_ALREADY_CANCELLED' USING ERRCODE = '22023';
  END IF;

  FOR v_item IN
    SELECT purchase.*
    FROM public.db_compras_historico AS purchase
    WHERE purchase.user_id = v_user_id
      AND purchase.id_lote = p_id_lote
      AND purchase.tipo_movimento = 'compra'
    ORDER BY purchase.id_insumo, purchase.id_compra
  LOOP
    SELECT supply.id_insumo, supply.estoque_atual, supply.custo_estimado_unitario
    INTO v_supply
    FROM public.db_insumos AS supply
    WHERE supply.user_id = v_user_id
      AND supply.id_insumo = v_item.id_insumo
    FOR UPDATE;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'PURCHASE_SUPPLY_NOT_FOUND' USING ERRCODE = 'P0002';
    END IF;

    v_new_stock := v_supply.estoque_atual - v_item.quantidade;
    IF v_new_stock < 0 THEN
      RAISE EXCEPTION 'INSUFFICIENT_SUPPLY_STOCK_FOR_CANCELLATION'
        USING ERRCODE = '22023';
    END IF;

    v_remaining_value :=
      v_supply.estoque_atual * v_supply.custo_estimado_unitario
      - v_item.valor_total;
    IF v_new_stock = 0 THEN
      v_new_cost := 0;
      IF v_remaining_value < -0.01 THEN
        RAISE EXCEPTION 'INVALID_RESULTING_SUPPLY_COST'
          USING ERRCODE = '22023';
      END IF;
    ELSE
      v_new_cost := pg_catalog.round(v_remaining_value / v_new_stock, 2);
      IF v_remaining_value < 0 OR v_new_cost < 0
        OR v_new_cost > 99999999.99
      THEN
        RAISE EXCEPTION 'INVALID_RESULTING_SUPPLY_COST'
          USING ERRCODE = '22023';
      END IF;
    END IF;

    UPDATE public.db_insumos
    SET
      estoque_atual = v_new_stock,
      custo_estimado_unitario = v_new_cost
    WHERE user_id = v_user_id
      AND id_insumo = v_item.id_insumo;

    INSERT INTO public.db_compras_historico (
      user_id,
      id_lote,
      data_compra,
      id_insumo,
      id_fornecedor,
      quantidade,
      unidade_compra,
      valor_total,
      valor_unitario,
      tipo_movimento,
      status,
      id_compra_compensada,
      motivo_cancelamento,
      cancelado_em,
      cancelado_por
    )
    VALUES (
      v_user_id,
      p_id_lote,
      NOW(),
      v_item.id_insumo,
      v_item.id_fornecedor,
      -v_item.quantidade,
      v_item.unidade_compra,
      -v_item.valor_total,
      v_item.valor_unitario,
      'cancelamento',
      'compensacao',
      v_item.id_compra,
      btrim(p_motivo),
      NOW(),
      v_user_id
    )
    RETURNING id_compra INTO v_cancelled_id;

    UPDATE public.db_compras_historico
    SET
      status = 'cancelada',
      motivo_cancelamento = btrim(p_motivo),
      cancelado_em = NOW(),
      cancelado_por = v_user_id
    WHERE user_id = v_user_id
      AND id_compra = v_item.id_compra;

    PERFORM public.recalculate_recipe_cost_after_supply_change(
      v_user_id,
      v_item.id_insumo,
      v_supply.custo_estimado_unitario,
      v_new_cost,
      v_cancelled_id,
      p_id_lote,
      'cancelamento'
    );
  END LOOP;

  RETURN TRUE;
END;
$$;

REVOKE ALL ON FUNCTION public.register_purchase_batch(INT, DATE, JSONB)
  FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.cancel_purchase_batch(UUID, TEXT)
  FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.register_purchase_batch(INT, DATE, JSONB)
  TO authenticated;
GRANT EXECUTE ON FUNCTION public.cancel_purchase_batch(UUID, TEXT)
  TO authenticated;
