CREATE TABLE IF NOT EXISTS public.db_fornecedores (
  id_fornecedor INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL DEFAULT auth.uid()
    REFERENCES auth.users (id) ON DELETE CASCADE,
  nome TEXT NOT NULL,
  endereco TEXT,
  ativo TEXT NOT NULL DEFAULT 'Sim' CHECK (ativo IN ('Sim', 'Não')),
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.db_fornecedores
  ADD COLUMN IF NOT EXISTS user_id UUID REFERENCES auth.users (id) ON DELETE CASCADE,
  ADD COLUMN IF NOT EXISTS ativo TEXT,
  ADD COLUMN IF NOT EXISTS criado_em TIMESTAMPTZ DEFAULT NOW(),
  ADD COLUMN IF NOT EXISTS atualizado_em TIMESTAMPTZ DEFAULT NOW();

DO $$
DECLARE
  owner_id UUID;
  sequence_name TEXT;
  maximum_id BIGINT;
BEGIN
  IF EXISTS (
    SELECT 1 FROM public.db_fornecedores WHERE user_id IS NULL
  ) THEN
    SELECT id
    INTO owner_id
    FROM auth.users
    WHERE deleted_at IS NULL
    ORDER BY created_at, id
    LIMIT 1;

    IF owner_id IS NULL THEN
      RAISE EXCEPTION
        'Cannot assign existing suppliers: no active Supabase users exist';
    END IF;

    UPDATE public.db_fornecedores
    SET user_id = owner_id
    WHERE user_id IS NULL;
  END IF;

  UPDATE public.db_fornecedores
  SET ativo = 'Sim'
  WHERE ativo IS NULL OR ativo NOT IN ('Sim', 'Não');

  sequence_name := pg_get_serial_sequence(
    'public.db_fornecedores',
    'id_fornecedor'
  );
  IF sequence_name IS NULL THEN
    sequence_name := 'public.db_fornecedores_id_fornecedor_seq';
    EXECUTE format('CREATE SEQUENCE IF NOT EXISTS %s', sequence_name);
    EXECUTE format(
      'ALTER TABLE public.db_fornecedores
       ALTER COLUMN id_fornecedor SET DEFAULT nextval(%L)',
      sequence_name
    );
    EXECUTE format(
      'ALTER SEQUENCE %s OWNED BY public.db_fornecedores.id_fornecedor',
      sequence_name
    );
  END IF;

  SELECT MAX(id_fornecedor) INTO maximum_id FROM public.db_fornecedores;
  IF maximum_id IS NOT NULL THEN
    PERFORM setval(sequence_name::regclass, maximum_id, true);
  END IF;
END;
$$;

